import { build } from 'esbuild';
import { access, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));

async function portablePage(assetBase) {
  const output = await build({
    absWorkingDir: root,
    entryPoints: ['src/main.jsx'],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2020'],
    outfile: 'portable.js',
    write: false,
    legalComments: 'inline',
    loader: { '.woff': 'dataurl', '.woff2': 'dataurl' },
    define: {
      'process.env.NODE_ENV': '"production"',
      'import.meta.env.BASE_URL': JSON.stringify(assetBase),
      // A downloaded offline preview never sends a checkout request.
      'import.meta.env.VITE_CHECKOUT_ENDPOINT': '""',
    },
  });
  const js = output.outputFiles.find(file => file.path.endsWith('.js')).text;
  const css = output.outputFiles.find(file => file.path.endsWith('.css')).text;
  return `<!doctype html>
<html lang="sv">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#191a17">
  <meta name="description" content="Ge dina favoritplagg nytt liv med Manveo. Ett komplett vävkit för att laga, skapa och förnya — en tråd i taget.">
  <title>Manveo – Väv enkelt & ge kläder nytt liv</title>
  <link rel="icon" type="image/svg+xml" href="${assetBase}favicon.svg">
  <link rel="preload" as="image" href="${assetBase}images/hero.png">
  <style>${css.replaceAll('</style', '<\\/style')}</style>
</head>
<body>
  <!-- Generated by npm run build:portable. Edit src/ rather than this file. -->
  <noscript>Aktivera JavaScript i din webbläsare för att visa Manveo.</noscript>
  <div id="root"></div>
  <script>${js.replaceAll('</script', '<\\/script')}</script>
</body>
</html>
`;
}

await writeFile(new URL('../manveo.html', import.meta.url), await portablePage('./public/'));
console.log('Created manveo.html: double-click to open, with images in public/.');

let hasProductionBuild = false;
try {
  await access(new URL('../dist/index.html', import.meta.url));
  hasProductionBuild = true;
} catch { /* A portable-only build does not require dist/. */ }
if (hasProductionBuild) {
  await writeFile(new URL('../dist/manveo.html', import.meta.url), await portablePage('./'));
  console.log('Created dist/manveo.html: local-file fallback for the production build.');
}
